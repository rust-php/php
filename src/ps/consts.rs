//! Constants for the string extensions (looked up by builtins::constant as a fallback).
use crate::value::Value;

pub fn constant(name: &str) -> Option<Value> {
    let n: i64 = match name {
        "CASE_LOWER" => 0,
        "CASE_UPPER" => 1,
        "PHP_URL_SCHEME" => 0,
        "PHP_URL_HOST" => 1,
        "PHP_URL_PORT" => 2,
        "PHP_URL_USER" => 3,
        "PHP_URL_PASS" => 4,
        "PHP_URL_PATH" => 5,
        "PHP_URL_QUERY" => 6,
        "PHP_URL_FRAGMENT" => 7,
        "PHP_QUERY_RFC1738" => 1,
        "PHP_QUERY_RFC3986" => 2,
        "PHP_ROUND_HALF_UP" => 1,
        "PHP_ROUND_HALF_DOWN" => 2,
        "PHP_ROUND_HALF_EVEN" => 3,
        "PHP_ROUND_HALF_ODD" => 4,
        "CRYPT_SALT_LENGTH" => 123,
        "CRYPT_STD_DES" | "CRYPT_EXT_DES" | "CRYPT_MD5" | "CRYPT_BLOWFISH" | "CRYPT_SHA256" | "CRYPT_SHA512" => 1,
        "HTML_SPECIALCHARS" => 0,
        "HTML_ENTITIES" => 1,
        "ENT_COMPAT" => 2,
        "ENT_QUOTES" => 3,
        "ENT_NOQUOTES" => 0,
        "ENT_IGNORE" => 4,
        "ENT_SUBSTITUTE" => 8,
        "ENT_DISALLOWED" => 128,
        "ENT_HTML401" => 0,
        "ENT_XML1" => 16,
        "ENT_XHTML" => 32,
        "ENT_HTML5" => 48,
        "CHAR_MAX" => 127,
        "LC_CTYPE" => 0,
        "LC_NUMERIC" => 1,
        "LC_TIME" => 2,
        "LC_COLLATE" => 3,
        "LC_MONETARY" => 4,
        "LC_MESSAGES" => 5,
        "LC_ALL" => 6,
        "MB_CASE_UPPER" => 0,
        "MB_CASE_LOWER" => 1,
        "MB_CASE_TITLE" => 2,
        "MB_CASE_FOLD" => 3,
        "MB_CASE_UPPER_SIMPLE" => 4,
        "MB_CASE_LOWER_SIMPLE" => 5,
        "MB_CASE_TITLE_SIMPLE" => 6,
        "MB_CASE_FOLD_SIMPLE" => 7,
        "PHP_MAXPATHLEN" => 4096,
        _ => return None,
    };
    Some(Value::Int(n))
}
